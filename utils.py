def _clean_col_name(c: str) -> str:
    """줄바꿈/따옴표/다중공백 제거 + 앞뒤 공백 제거"""
    s = str(c)
    s = s.replace("\n", "").replace("\r", "")
    s = s.replace('"', "").replace("'", "")
    s = re.sub(r"\s+", " ", s).strip()
    return s

